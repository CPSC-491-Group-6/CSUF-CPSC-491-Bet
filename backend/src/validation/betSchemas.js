import { z } from "zod";

/**
 * Validate answer choices supplied when creating a bet.
 *
 * The SQLite schema allows labels of 1-150 characters and enforces
 * case-insensitive uniqueness within each bet.
 *
 * Keep the maximum option count bounded to prevent excessive
 * records from being created by one request.
 */
export const betOptionsSchema = z
  .array(z.string().trim().min(1).max(150))
  .min(2, "Provide at least two answer options.")
  .max(20, "Provide no more than 20 answer options.")
  .superRefine((options, context) => {
    const seen = new Set();

    for (const [index, label] of options.entries()) {
      const normalizedLabel = label.toLowerCase();

      if (seen.has(normalizedLabel)) {
        context.addIssue({
          code: "custom",
          path: [index],
          message: "Answer options must be unique.",
        });
      }

      seen.add(normalizedLabel);
    }
  });

/**
 * Accept creator-controlled fields only.
 *
 * Bet IDs, ownership, join codes, option IDs, and option positions
 * are generated by the backend.
 *
 * Answer options are optional for compatibility with existing
 * Create Bet clients and previously supported workflows.
 */
export const createBetSchema = z
  .object({
    title: z.string().trim().min(1).max(150),

    description: z.string().trim().max(2000).default(""),

    max_participants: z.number().int().min(2).max(100).default(2),

    visibility: z.enum(["public", "private"]).default("private"),

    options: betOptionsSchema.optional(),
  })
  .strict();

/**
 * Accept stored legacy codes as well as newly generated
 * 12-character hexadecimal join codes.
 */
export const joinCodeSchema = z
  .string()
  .trim()
  .min(1)
  .max(64)
  .regex(/^[A-Za-z0-9_-]+$/, "Join code contains invalid characters.");
